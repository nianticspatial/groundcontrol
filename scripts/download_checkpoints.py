#!/usr/bin/env python3
"""Download GroundControl + dependency checkpoints and write paths.yaml."""

from __future__ import annotations

import argparse
import subprocess
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUTDIR = ROOT / "checkpoints"
PATHS_YAML = ROOT / "src" / "groundcontrol" / "configs" / "paths.yaml"

GC_REPO = "AkshayKrishnan/groundcontrol"
GC_FILE = "groundcontrol.ckpt"
SEVA_REPO = "stabilityai/stable-virtual-camera"
SEVA_WEIGHT = "modelv1.1.safetensors"
VAE_REPO = "stabilityai/stable-diffusion-2-1-base"
DINOV3_GIT = "https://github.com/facebookresearch/dinov3.git"
DINO_URL = "https://dl.fbaipublicfiles.com/dino/dino_vitbase16_pretrain/dino_vitbase16_pretrain.pth"
SAM_URL = "https://dl.fbaipublicfiles.com/segment_anything/sam_vit_h_4b8939.pth"


def _hf():
    try:
        from huggingface_hub import hf_hub_download, snapshot_download
    except ImportError as e:
        raise SystemExit(
            "huggingface_hub is required. Install the groundcontrol env first."
        ) from e
    return hf_hub_download, snapshot_download


def download_url(url: str, dest: Path) -> Path:
    dest.parent.mkdir(parents=True, exist_ok=True)
    if dest.exists() and dest.stat().st_size > 0:
        print(f"[skip] {dest}")
        return dest
    print(f"[download] {url} -> {dest}")
    urllib.request.urlretrieve(url, dest)
    return dest


def download_groundcontrol(outdir: Path) -> Path:
    hf_hub_download, _ = _hf()
    dest_dir = outdir
    dest_dir.mkdir(parents=True, exist_ok=True)
    path = hf_hub_download(
        repo_id=GC_REPO,
        filename=GC_FILE,
        local_dir=str(dest_dir),
    )
    print(f"[ok] GroundControl -> {path}")
    return Path(path)


def download_seva(outdir: Path) -> Path:
    hf_hub_download, _ = _hf()
    seva_dir = outdir / "seva"
    seva_dir.mkdir(parents=True, exist_ok=True)
    for name in (SEVA_WEIGHT, "config.yaml"):
        path = hf_hub_download(
            repo_id=SEVA_REPO,
            filename=name,
            local_dir=str(seva_dir),
        )
        print(f"[ok] SEVA {name} -> {path}")
    return seva_dir


def download_vae(outdir: Path) -> Path:
    _, snapshot_download = _hf()
    vae_root = outdir / "sd21"
    snapshot_download(
        repo_id=VAE_REPO,
        allow_patterns=["vae/*"],
        local_dir=str(vae_root),
    )
    print(f"[ok] SD 2.1 VAE -> {vae_root}/vae")
    return vae_root


def download_openclip(outdir: Path) -> Path:
    cache_dir = outdir / "open_clip"
    cache_dir.mkdir(parents=True, exist_ok=True)
    print(f"[download] OpenCLIP ViT-H/14 laion2b_s32b_b79k -> {cache_dir}")
    import open_clip

    open_clip.create_model_and_transforms(
        "ViT-H-14",
        pretrained="laion2b_s32b_b79k",
        cache_dir=str(cache_dir),
    )
    print(f"[ok] OpenCLIP cache -> {cache_dir}")
    return cache_dir


def clone_dinov3(outdir: Path) -> Path:
    repo = outdir / "dinov3"
    if (repo / "hubconf.py").exists():
        print(f"[skip] DINOv3 repo -> {repo}")
        return repo
    print(f"[clone] {DINOV3_GIT} -> {repo}")
    subprocess.run(
        ["git", "clone", "--depth", "1", DINOV3_GIT, str(repo)],
        check=True,
    )
    return repo


def download_dinov3_weights(outdir: Path, url: str | None) -> Path | None:
    dest = outdir / "dinov3_vitl16.pth"
    if dest.exists() and dest.stat().st_size > 0:
        print(f"[skip] DINOv3 weights -> {dest}")
        return dest
    if not url:
        print(
            "[warn] DINOv3 weights are gated. Request access at\n"
            "       https://ai.meta.com/resources/models-and-libraries/dinov3-downloads/\n"
            "       then re-run with --dinov3-url <your-download-url>"
        )
        return None
    return download_url(url, dest)


def write_paths_yaml(
    outdir: Path,
    *,
    checkpoint: Path,
    seva: Path,
    vae: Path,
    clip: Path,
    dinov3_repo: Path,
    dinov3_weights: Path | None,
    dino: Path | None,
    sam: Path | None,
    paths_yaml: Path,
) -> None:
    def q(p: Path | None) -> str:
        if p is None:
            return "null"
        return str(p.resolve())

    # Preserve existing data paths if paths.yaml already exists.
    data_dir = "/path/to/metropolis"
    satellite_dir = "/path/to/metropolis/sat_preprocessed"
    output_dir = "outputs/metropolis"
    if paths_yaml.exists():
        try:
            from omegaconf import OmegaConf

            prev = OmegaConf.load(paths_yaml)
            data_dir = str(prev.get("data_dir", data_dir))
            satellite_dir = str(prev.get("satellite_dir", satellite_dir))
            output_dir = str(prev.get("output_dir", output_dir))
        except Exception:
            pass

    text = f"""# Auto-generated by scripts/download_checkpoints.py
# Edit data_dir / satellite_dir for your local Metropolis data.

checkpoint_path: {q(checkpoint)}
output_dir: {output_dir}

pretrained_weights_path: {q(seva)}
vae_ckpt_path: {q(vae)}
clip_hf_hub_path: {q(clip)}

data_dir: {data_dir}
satellite_dir: {satellite_dir}

dinov3_repo: {q(dinov3_repo)}
dinov3_weights: {q(dinov3_weights)}

# Optional — required only when validation.semeval is true
dino_weights: {q(dino)}
sam_weights: {q(sam)}
"""
    paths_yaml.parent.mkdir(parents=True, exist_ok=True)
    paths_yaml.write_text(text)
    print(f"[ok] wrote {paths_yaml}")


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Download GroundControl checkpoints and write paths.yaml."
    )
    parser.add_argument(
        "--outdir",
        type=Path,
        default=DEFAULT_OUTDIR,
        help=f"Directory for downloaded weights (default: {DEFAULT_OUTDIR})",
    )
    parser.add_argument(
        "--paths-yaml",
        type=Path,
        default=PATHS_YAML,
        help=f"paths.yaml to write (default: {PATHS_YAML})",
    )
    parser.add_argument(
        "--dinov3-url",
        type=str,
        default=None,
        help="Direct URL for dinov3_vitl16.pth (from Meta after access approval).",
    )
    parser.add_argument(
        "--with-semeval",
        action="store_true",
        help="Also download DINOv1 and SAM weights for semantic eval.",
    )
    parser.add_argument(
        "--skip-openclip",
        action="store_true",
        help="Skip OpenCLIP download (still sets clip_hf_hub_path to outdir/open_clip).",
    )
    args = parser.parse_args()
    outdir = args.outdir.expanduser().resolve()
    outdir.mkdir(parents=True, exist_ok=True)

    checkpoint = download_groundcontrol(outdir)
    seva = download_seva(outdir)
    vae = download_vae(outdir)
    clip = outdir / "open_clip"
    if args.skip_openclip:
        clip.mkdir(parents=True, exist_ok=True)
        print(f"[skip] OpenCLIP download; cache dir {clip}")
    else:
        clip = download_openclip(outdir)

    dinov3_repo = clone_dinov3(outdir)
    dinov3_weights = download_dinov3_weights(outdir, args.dinov3_url)

    dino = sam = None
    if args.with_semeval:
        dino = download_url(DINO_URL, outdir / "dino_vitbase16_pretrain.pth")
        sam = download_url(SAM_URL, outdir / "sam_vit_h_4b8939.pth")

    write_paths_yaml(
        outdir,
        checkpoint=checkpoint,
        seva=seva,
        vae=vae,
        clip=clip,
        dinov3_repo=dinov3_repo,
        dinov3_weights=dinov3_weights,
        dino=dino,
        sam=sam,
        paths_yaml=args.paths_yaml.expanduser().resolve(),
    )

    if dinov3_weights is None:
        print(
            "\nDINOv3 weights still missing — inference will fail until you pass --dinov3-url.",
            file=sys.stderr,
        )


if __name__ == "__main__":
    main()
